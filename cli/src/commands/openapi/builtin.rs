    #[test]
    fn class_names_are_identifiers_and_esm_marks_the_package_a_module() {
        assert!(is_identifier("NotesClient") && is_identifier("_c$1"));
        assert!(!is_identifier("1Client") && !is_identifier("notes-client") && !is_identifier(""));
        let dir = std::env::temp_dir().join(format!("cufflink-esm-{}", std::process::id()));
        std::fs::create_dir_all(&dir).expect("dir");
        let manifest = ServiceManifest {
            name: "loans-service".into(),
            version: Some("1.2.0".into()),
            ..Default::default()
        };
        let (_, fresh) = package_json(&dir, &manifest).expect("package");
        assert_eq!(
            serde_json::from_str::<Value>(&fresh).expect("json"),
            json!({"name": "loans-service-client", "version": "1.2.0", "type": "module"})
        );
        std::fs::write(
            dir.join("package.json"),
            r#"{"name": "@acme/notes", "private": true}"#,
        )
        .expect("write");
        let (_, merged) = package_json(&dir, &manifest).expect("package");
        assert_eq!(
            serde_json::from_str::<Value>(&merged).expect("json"),
            json!({"name": "@acme/notes", "private": true, "type": "module"})
        );
        let _ = std::fs::remove_dir_all(dir);
    }
